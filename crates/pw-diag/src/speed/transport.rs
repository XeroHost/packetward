//! The seam between the speed-test logic and the network.
//!
//! Everything in this module tree is written against [`SpeedTransport`]; the real implementation (reqwest, feature
//! `speed`) and the scripted [`FakeTransport`](super::fake::FakeTransport) used by the tests both implement it.
//! A transport performs exactly one HTTP exchange per call and knows nothing about streams, warm-up or budgets.
//!
//! Cancellation is by dropping: the engine drops the future of an in-flight call (`select!` on the
//! [`CancelToken`](crate::CancelToken), `JoinSet::abort_all`), which must abort the request and close the
//! connection. A transport therefore must not spawn detached work that keeps moving bytes.

use std::future::Future;
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::Arc;
use std::time::Duration;

use super::error::TransportError;
use super::server::{ServerEndpoint, ServerInfo};

/// Shared counter of payload bytes moved by all streams of one run. Transports call [`ByteMeter::add`] as data
/// arrives (download) or is handed to the HTTP stack (upload); the engine samples it once per bucket. Cloning
/// shares the counter.
#[derive(Debug, Clone, Default)]
pub struct ByteMeter(Arc<AtomicU64>);

impl ByteMeter {
    /// A new counter at zero.
    pub fn new() -> Self {
        Self::default()
    }

    /// Count `bytes` more.
    pub fn add(&self, bytes: u64) {
        self.0.fetch_add(bytes, Ordering::Relaxed);
    }

    /// Bytes counted so far.
    pub fn total(&self) -> u64 {
        self.0.load(Ordering::Relaxed)
    }
}

/// One `GET /download?bytes=N&test=<id>`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct DownloadRequest<'a> {
    /// Exact number of bytes to request.
    pub bytes: u64,
    /// The run's id; every stream of the run sends the same one.
    pub test_id: &'a str,
}

/// One `POST /upload?test=<id>` with a body of exactly `bytes` generated bytes.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct UploadRequest<'a> {
    /// Body length.
    pub bytes: u64,
    /// The run's id; every stream of the run sends the same one.
    pub test_id: &'a str,
}

/// The network operations the speed test needs.
pub trait SpeedTransport: Send + Sync + 'static {
    /// `GET /ping`. Returns the round-trip time measured by the transport.
    fn ping(
        &self,
        server: &ServerEndpoint,
        timeout: Duration,
    ) -> impl Future<Output = Result<Duration, TransportError>> + Send;

    /// `GET /info`.
    fn info(
        &self,
        server: &ServerEndpoint,
        timeout: Duration,
    ) -> impl Future<Output = Result<ServerInfo, TransportError>> + Send;

    /// `GET /download`: read the whole body into a sink, counting every chunk on `meter` as it arrives. Returns the
    /// bytes received. No timeout of its own (bin tests run for hours): the engine bounds the run and drops the
    /// future.
    fn download(
        &self,
        server: &ServerEndpoint,
        request: &DownloadRequest<'_>,
        meter: &ByteMeter,
    ) -> impl Future<Output = Result<u64, TransportError>> + Send;

    /// `POST /upload`: send `request.bytes` generated bytes from a reusable buffer, counting on `meter` as chunks
    /// are handed to the HTTP stack. Returns the byte count the server reports.
    fn upload(
        &self,
        server: &ServerEndpoint,
        request: &UploadRequest<'_>,
        meter: &ByteMeter,
    ) -> impl Future<Output = Result<u64, TransportError>> + Send;
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn meter_clones_share_one_counter() {
        let meter = ByteMeter::new();
        let other = meter.clone();
        meter.add(5);
        other.add(7);
        assert_eq!(meter.total(), 12);
        assert_eq!(other.total(), 12);
    }
}
