//! Download payload generation.
//!
//! A small pool of pseudo-random frames is generated once at startup. A download is a sequence of
//! reference-counted slices of that pool, so producing a byte costs no CPU and no allocation, nothing
//! touches the disk and memory use is constant (pool size + one frame in flight per stream) no matter how
//! large the download is. The data is incompressible for any compressor window smaller than the pool.
//! The generator is a fast non-cryptographic PRNG; the data carries no secrets.

use std::hash::{BuildHasher, Hasher};
use std::pin::Pin;
use std::sync::atomic::Ordering;
use std::sync::Arc;
use std::task::{Context, Poll};
use std::time::Instant;

use bytes::Bytes;
use http_body::{Body, Frame, SizeHint};

use crate::ip::anonymize;
use crate::limits::{Stats, TransferPermit};

/// Bytes per body frame (one `write` worth of data).
pub const FRAME_LEN: usize = 128 * 1024;
const POOL_FRAMES: usize = 8;

/// The shared pool of random frames.
#[derive(Debug)]
pub struct Payload {
    pool: Bytes,
}

impl Payload {
    /// Generate the pool from `seed` (use [`Payload::random`] in production).
    pub fn new(seed: u64) -> Self {
        let mut state = seed;
        let mut buf = vec![0u8; FRAME_LEN * POOL_FRAMES];
        for chunk in buf.as_chunks_mut::<8>().0 {
            *chunk = splitmix64(&mut state).to_le_bytes();
        }
        Self {
            pool: Bytes::from(buf),
        }
    }

    /// A pool seeded from the process-random `RandomState`.
    pub fn random() -> Self {
        let seed = std::collections::hash_map::RandomState::new()
            .build_hasher()
            .finish();
        Self::new(seed)
    }

    fn frame(&self, index: usize) -> Bytes {
        let i = index % POOL_FRAMES;
        self.pool.slice(i * FRAME_LEN..(i + 1) * FRAME_LEN)
    }

    /// Number of distinct frames (for tests).
    pub fn frames(&self) -> usize {
        POOL_FRAMES
    }

    /// Build the response body for a download of exactly `len` bytes.
    pub fn body(self: &Arc<Self>, len: u64, ctx: DownloadContext) -> DownloadBody {
        // Different starting frames per stream so parallel streams do not carry identical data.
        let start = ctx.start_frame % POOL_FRAMES;
        DownloadBody {
            payload: Arc::clone(self),
            requested: len,
            remaining: len,
            next: start,
            ctx,
            started: Instant::now(),
            finished: false,
        }
    }
}

fn splitmix64(state: &mut u64) -> u64 {
    *state = state.wrapping_add(0x9E37_79B9_7F4A_7C15);
    let mut z = *state;
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    z ^ (z >> 31)
}

/// Everything a download body needs besides the payload.
pub struct DownloadContext {
    /// Slot and byte reservation; released when the body is dropped.
    pub permit: TransferPermit,
    /// Shared counters.
    pub stats: Arc<Stats>,
    /// Hard deadline for the whole transfer.
    pub deadline: Instant,
    /// Frame index to start from.
    pub start_frame: usize,
    /// Client label for the completion log line (already anonymized as configured).
    pub client_label: String,
}

/// Body errors.
#[derive(Debug, thiserror::Error)]
pub enum BodyError {
    /// The transfer exceeded `server.max_transfer_secs`.
    #[error("transfer exceeded the maximum duration")]
    Deadline,
}

/// A streaming body of generated bytes with an exact size hint (so hyper sends `Content-Length`).
///
/// Dropping it (client disconnect, shutdown, or normal completion) stops generation at once and frees the
/// limiter slot; unsent bytes are refunded to the client's budget.
pub struct DownloadBody {
    payload: Arc<Payload>,
    requested: u64,
    remaining: u64,
    next: usize,
    ctx: DownloadContext,
    started: Instant,
    finished: bool,
}

impl Body for DownloadBody {
    type Data = Bytes;
    type Error = BodyError;

    fn poll_frame(
        mut self: Pin<&mut Self>,
        _cx: &mut Context<'_>,
    ) -> Poll<Option<Result<Frame<Bytes>, BodyError>>> {
        let this = &mut *self;
        if this.remaining == 0 {
            this.finished = true;
            return Poll::Ready(None);
        }
        if Instant::now() >= this.ctx.deadline {
            return Poll::Ready(Some(Err(BodyError::Deadline)));
        }
        let mut frame = this.payload.frame(this.next);
        this.next = this.next.wrapping_add(1);
        if (frame.len() as u64) > this.remaining {
            frame.truncate(this.remaining as usize);
        }
        let n = frame.len() as u64;
        this.remaining -= n;
        this.ctx.permit.add_used(n);
        this.ctx
            .stats
            .generated_bytes
            .fetch_add(n, Ordering::Relaxed);
        Poll::Ready(Some(Ok(Frame::data(frame))))
    }

    fn is_end_stream(&self) -> bool {
        self.remaining == 0
    }

    fn size_hint(&self) -> SizeHint {
        SizeHint::with_exact(self.remaining)
    }
}

impl Drop for DownloadBody {
    fn drop(&mut self) {
        let sent = self.requested - self.remaining;
        tracing::info!(
            client = %self.ctx.client_label,
            requested = self.requested,
            sent,
            completed = self.finished || self.remaining == 0,
            millis = self.started.elapsed().as_millis() as u64,
            "download finished"
        );
    }
}

/// Re-export for handlers that need to label clients consistently.
pub fn client_label(ip: std::net::IpAddr, full: bool) -> String {
    if full {
        ip.to_string()
    } else {
        anonymize(ip)
    }
}

#[cfg(test)]
mod tests {
    use std::time::Duration;

    use http_body_util_lite::collect_len;

    use super::*;
    use crate::config::{LimitsConfig, ServerConfig};
    use crate::limits::Limiter;

    // A tiny stand-in for http-body-util's BodyExt so we do not need another dependency.
    mod http_body_util_lite {
        use std::future::poll_fn;
        use std::pin::Pin;

        use http_body::Body;

        pub async fn collect_len<B: Body<Data = bytes::Bytes> + Unpin>(
            mut body: B,
        ) -> (u64, Vec<bytes::Bytes>)
        where
            B::Error: std::fmt::Debug,
        {
            let mut total = 0;
            let mut first = Vec::new();
            while let Some(frame) = poll_fn(|cx| Pin::new(&mut body).poll_frame(cx)).await {
                let data = frame.unwrap().into_data().unwrap();
                total += data.len() as u64;
                if first.len() < 3 {
                    first.push(data);
                }
            }
            (total, first)
        }
    }

    fn ctx(deadline: Instant) -> (DownloadContext, Arc<Limiter>) {
        let stats = Arc::new(Stats::default());
        let lim = Limiter::new(
            &LimitsConfig::default(),
            &ServerConfig::default(),
            Arc::clone(&stats),
            Instant::now(),
        );
        let permit = lim
            .begin_transfer("127.0.0.1".parse().unwrap(), None, 0, Instant::now())
            .unwrap();
        (
            DownloadContext {
                permit,
                stats,
                deadline,
                start_frame: 3,
                client_label: "test".into(),
            },
            lim,
        )
    }

    #[test]
    fn pool_is_not_constant_and_frames_differ() {
        let p = Payload::new(42);
        assert_ne!(p.frame(0), p.frame(1));
        assert!(p.frame(0).iter().any(|&b| b != 0));
        // Same seed -> same pool (deterministic for tests), different seed -> different pool.
        assert_eq!(Payload::new(42).frame(2), p.frame(2));
        assert_ne!(Payload::new(43).frame(2), p.frame(2));
        assert_eq!(p.frames(), POOL_FRAMES);
    }

    #[tokio::test]
    async fn body_yields_exactly_n_bytes_for_odd_sizes() {
        let p = Arc::new(Payload::new(1));
        for len in [
            1u64,
            7,
            FRAME_LEN as u64 - 1,
            FRAME_LEN as u64,
            FRAME_LEN as u64 + 1,
            3 * FRAME_LEN as u64 + 5,
        ] {
            let (c, _lim) = ctx(Instant::now() + Duration::from_secs(60));
            let body = p.body(len, c);
            assert_eq!(body.size_hint().exact(), Some(len));
            let (total, _) = collect_len(body).await;
            assert_eq!(total, len);
        }
    }

    #[tokio::test]
    async fn dropping_the_body_releases_the_slot_and_counts_only_generated_bytes() {
        let p = Arc::new(Payload::new(1));
        let (c, lim) = ctx(Instant::now() + Duration::from_secs(60));
        let stats = Arc::clone(&c.stats);
        let mut body = Box::pin(p.body(1 << 40, c));
        let frame = std::future::poll_fn(|cx| body.as_mut().poll_frame(cx))
            .await
            .unwrap()
            .unwrap();
        assert_eq!(frame.into_data().unwrap().len(), FRAME_LEN);
        assert_eq!(lim.stats().active_streams.load(Ordering::Relaxed), 1);
        drop(body);
        assert_eq!(lim.stats().active_streams.load(Ordering::Relaxed), 0);
        assert_eq!(
            stats.generated_bytes.load(Ordering::Relaxed),
            FRAME_LEN as u64
        );
    }

    #[tokio::test]
    async fn deadline_aborts_the_body() {
        let p = Arc::new(Payload::new(1));
        let (c, _lim) = ctx(Instant::now() - Duration::from_secs(1));
        let mut body = Box::pin(p.body(10, c));
        let r = std::future::poll_fn(|cx| body.as_mut().poll_frame(cx))
            .await
            .unwrap();
        assert!(matches!(r, Err(BodyError::Deadline)));
    }

    /// Pure generation rate without any network: `cargo test --release -p pw-speed-server --lib -- --ignored --nocapture`.
    #[tokio::test]
    #[ignore = "benchmark; run explicitly in release mode"]
    async fn generation_rate_64mib_without_network() {
        let p = Arc::new(Payload::new(9));
        let (c, _lim) = ctx(Instant::now() + Duration::from_secs(60));
        let body = p.body(64 * 1024 * 1024, c);
        let started = Instant::now();
        let (total, _) = collect_len(body).await;
        let secs = started.elapsed().as_secs_f64();
        assert_eq!(total, 64 * 1024 * 1024);
        println!(
            "generated 64 MiB in {:.1} ms = {:.1} GB/s",
            secs * 1e3,
            total as f64 / secs / 1e9
        );
    }
}
